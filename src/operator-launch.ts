import { resolve } from "node:path";
import { type Seat, desk, exists, project, readYaml } from "./core";
import { readRuntimeState } from "./runtime-state";

type Receipt = Record<string, string | undefined>;
type Recorded = { recorded_at: string; text: string };

/** The single generated relaunch command: the Flow launcher resolves the pane, so no --pane, --resume, or hand-edited binding is involved. */
export const canonicalLaunchCommand = (address: string, herdrSession: string) => `atdd-flow pi runtime launch ${address} --herdr-session ${herdrSession}`;

/** Only operator@<project> on the project's primary main checkout is the supported operator seat. */
export async function isExactOperatorSeat(root: string, record: Seat, address: string) {
  if (record.address !== address || record.role !== "operator" || address !== `operator@${record.project}` || record.branch !== "main") return false;
  const config = await project(root, record.project);
  return Boolean(config.repository && resolve(record.worktree) === resolve(config.repository));
}

/** The text appended to `handover show`; the recorded handover itself is never rewritten. */
export async function operatorRelaunchSection(root: string, record: Seat) {
  const locator = record.runtime?.addresses.herdr;
  const session = (typeof locator === "object" ? locator.session : undefined) ?? (await desk(root)).herdr_session;
  const command = session ? canonicalLaunchCommand(record.address, session) : "UNAVAILABLE: no Herdr session is recorded for this seat or Desk.";
  return `\nCANONICAL RELAUNCH COMMAND (generated by Flow; run it in a vacant shell pane after this Pi exits, then run \`atdd-flow handover resumed ${record.address}\`):\n${command}\n`;
}

const notBefore = (value: string | undefined, floor: string | undefined) => Boolean(value && floor && Date.parse(value) >= Date.parse(floor));
const handoverSession = (handover: Recorded | undefined) => handover?.text.match(/^Runtime:[^|]*\|\s*([^|\s]+)/m)?.[1];

async function readReceipt(path: string | undefined): Promise<Receipt | undefined> {
  return path && await exists(path) ? readYaml<Receipt>(path) : undefined;
}

function nativeBinding(record: Seat) {
  const runtime = record.runtime;
  return runtime?.application === "herdr" && runtime.wake === "native" && typeof runtime.addresses.herdr === "object";
}

function receiptMatchesBinding(record: Seat, receipt: Receipt | undefined) {
  const runtime = record.runtime, locator = runtime?.addresses.herdr;
  if (!receipt || !runtime?.pi_session || typeof locator !== "object") return false;
  return receipt.schema === "atdd-flow/pi-runtime-launch-receipt/v1" && receipt.seat === record.address
    && receipt.pi_session === runtime.pi_session && receipt.pi_session_path === runtime.pi_session_path
    && receipt.herdr_session === locator.session && receipt.pane === locator.pane;
}

async function heartbeatMatches(root: string, record: Seat, handover: Recorded | undefined) {
  const state = await readRuntimeState(root, record.address);
  return Boolean(state && state.seat === record.address && state.pi_session === record.runtime?.pi_session && notBefore(state.heartbeat_at, handover?.recorded_at));
}

/**
 * An operator successor has no Path-A request. It is reported resumed only when the
 * launcher's fresh receipt, the native-wake binding, and a matching heartbeat all agree.
 */
export async function operatorActivation(root: string, record: Seat, handover: Recorded | undefined) {
  const receipt = await readReceipt(record.runtime?.launch_receipt);
  const session = record.runtime?.pi_session;
  const checks: Array<[string, boolean]> = [
    ["recorded handover", Boolean(handover)],
    ["native delivery", nativeBinding(record)],
    ["launcher receipt", receiptMatchesBinding(record, receipt)],
    ["fresh receipt", notBefore(receipt?.created_at, handover?.recorded_at)],
    ["fresh heartbeat", await heartbeatMatches(root, record, handover)],
    ["fresh Pi session", Boolean(session) && session !== handoverSession(handover)],
  ];
  const discrepancies = checks.filter(([, ok]) => !ok).map(([name]) => name);
  return { verified: checks.length - discrepancies.length, total: checks.length, discrepancies };
}
